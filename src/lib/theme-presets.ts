// Get a preset by ID
export function getPresetById(id: string): ThemePreset | undefined {
  return themePresets.find((p) => p.id === id);
}

// Get default theme colors (used when no custom theme is set)
export function getDefaultColors(mode: "light" | "dark"): ThemeColors {
  const defaultPreset = getPresetById("default");
  return defaultPreset ? defaultPreset[mode] : themePresets[0][mode];
}
